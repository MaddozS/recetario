/**
 * Registro explícito de íconos lucide usados por la app.
 *
 * La clave es el nombre en kebab-case tal como lo escriben los llamados
 * (`<Icon name="lucide:book-open" />`), sin el prefijo `lucide:`. Los imports
 * nombrados permiten que el bundler elimine el resto del paquete.
 *
 * Tres claves conservan el vocabulario del árbol Astro pero apuntan al nombre
 * canónico actual de lucide (`alert-triangle` → `TriangleAlert`,
 * `arrow-up-circle` → `CircleArrowUp`, `check-circle` → `CircleCheck`): los
 * alias deprecados ya no se exportan en `@lucide/vue`. `trash-2` → `Trash`
 * porque lucide fusionó ambos glifos (mismo trazado que en `@lucide/astro@1.28`).
 */
